#!/usr/bin/env python3
"""Export the results of the article to the raw_data format of the MLV Tools viewer.

Reads only the data deposit (the export of src/08_export_zenodo.py, the files archived in
Zenodo) and writes the files that the viewer (https://github.com/enheragu/mlv-tools) loads from its
raw_data/ folder:

  accuracy_data_raw.yaml           MNIST accuracy (%) per model: the main study and the batch size
                                   variants of CNN_14L, 400 trials each.
  ablation_accuracy_data_raw.yaml  MNIST accuracy (%) per ablation condition, all its trials.
  mnist_ablation_table.csv         MNIST ablation trials of the iterations complete for the nine
                                   conditions, one row per trial; the index is the iteration, so the
                                   viewer pairs the conditions by seed.
  mAP50_data_raw.yaml, mAP50-95_data_raw.yaml, P_data_raw.yaml, R_data_raw.yaml
                                   Final evaluation of the valid YOLOv8 runs per group, as fractions:
                                   mAP of all classes, precision and recall of the person class.
  detection_ablation_table.csv     The valid LLVIP runs with the factors of the equalization ablation
                                   (fusion, visible and thermal equalization), one row per run.

Models and groups are written in the display order of the viewer: the MNIST models by architecture
and then the batch size variants, and the YOLOv8 groups in the order of yolo_groups.csv, which is the
order of the figures of the article. Within a model or group, the trials keep the order of the
deposit, which the Bootstrap simulations depend on.

Usage, from the root of the repository:
    python3 scripts/export_web_data.py zenodo_export <mlv-tools>/raw_data
"""
import csv
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "article"))
from ablation_data import llvip_ablation, mnist_ablation  # noqa: E402

# Display order of the viewer: architectures, then the batch size variants of CNN_14L.
MAIN_MODEL_ORDER = ["CNN_3L", "CNN_4L", "CNN_5L", "CNN_14L", "DNN_6L", "HiddenLayerPerceptron",
                    "SimplePerceptron", "BatchNormMaxoutNetInNet",
                    "CNN_14L_B10", "CNN_14L_B25", "CNN_14L_B50", "CNN_14L_B80"]

# Viewer file -> column of yolo_runs.csv. mAP over all classes; precision and recall of the person
# class (in these runs the two are equal, see the README of the deposit).
YOLO_METRICS = {"mAP50": "mAP50", "mAP50-95": "mAP50_95", "P": "P_person", "R": "R_person"}

HEADER = "Generated by scripts/export_web_data.py of mnist-learning-playground from the data deposit - do not edit by hand."


def _read(export_dir, name):
    # The default float parser of pandas can be one ulp off; round_trip gives the values exactly as written in the deposit
    return pd.read_csv(os.path.join(export_dir, name), float_precision="round_trip")


def _write_yaml(path, series_by_name, description):
    with open(path, "w") as fh:
        fh.write("# %s\n# %s\n" % (description, HEADER))
        for name, values in series_by_name.items():
            fh.write("%s: [%s]\n" % (name, ", ".join(repr(float(v)) for v in values)))
    return {name: len(values) for name, values in series_by_name.items()}


def _write_csv(path, frame, columns, integer_columns):
    # Integer columns are read as floats by pandas when the deposit has empty cells in them
    def cell(column, value):
        if isinstance(value, str):
            return value
        return str(int(value)) if column in integer_columns else repr(float(value))

    with open(path, "w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(columns)
        for row in frame[columns].itertuples(index=False):
            writer.writerow([cell(column, value) for column, value in zip(columns, row)])
    return len(frame)


def _report(path, counts):
    print("wrote %s  (%s)" % (path, ", ".join("%s=%d" % (k, n) for k, n in counts.items())))


def export_mnist(export_dir, out_dir):
    trials = _read(export_dir, "mnist_trials.csv")

    main = trials[trials["experiment"].isin(["main", "batch_size"])]
    present = list(dict.fromkeys(main["condition"]))
    order = [m for m in MAIN_MODEL_ORDER if m in present] + [m for m in present if m not in MAIN_MODEL_ORDER]
    accuracy = {m: (main.loc[main["condition"] == m, "accuracy"] * 100).tolist() for m in order}
    out = os.path.join(out_dir, "accuracy_data_raw.yaml")
    _report(out, _write_yaml(out, accuracy, "MNIST test accuracy (%) per model, one value per trial."))

    ablation = trials[trials["experiment"] == "ablation"]
    conditions = sorted(ablation["condition"].unique(),
                        key=lambda c: (int(ablation.loc[ablation["condition"] == c, "batch_size"].iloc[0]),
                                       float(ablation.loc[ablation["condition"] == c, "learning_rate"].iloc[0])))
    ablation_accuracy = {c: (ablation.loc[ablation["condition"] == c, "accuracy"] * 100).tolist() for c in conditions}
    out = os.path.join(out_dir, "ablation_accuracy_data_raw.yaml")
    _report(out, _write_yaml(out, ablation_accuracy,
                             "MNIST test accuracy (%) per ablation condition of CNN_14L, one value per trial."))

    # Rows and columns of the article table; the values are taken from the exact read, by trial, and the rows are
    # ordered by iteration, batch size and learning rate, as the analysis code reads the ablation log
    table = mnist_ablation(export_dir).rename(columns={"iteration": "index"})
    table["accuracy"] = (table["trial_id"].map(trials.set_index("trial_id")["accuracy"]) * 100).round(2)
    table = table.sort_values(["index", "batch_size", "learning_rate"], kind="stable")
    out = os.path.join(out_dir, "mnist_ablation_table.csv")
    n = _write_csv(out, table, ["index", "seed", "batch_size", "learning_rate", "accuracy"], ("index", "seed", "batch_size"))
    print("wrote %s  (%d rows, %d iterations)" % (out, n, table["index"].nunique()))


def export_yolo(export_dir, out_dir):
    groups = _read(export_dir, "yolo_groups.csv")["group"].tolist()
    runs = _read(export_dir, "yolo_runs.csv")
    for metric, column in YOLO_METRICS.items():
        values = {g: runs.loc[runs["group"] == g, column].tolist() for g in groups}
        out = os.path.join(out_dir, "%s_data_raw.yaml" % metric)
        _report(out, _write_yaml(out, values, "YOLOv8 %s of the final evaluation of the valid runs, per group." % metric))

    # Rows, factors and order of the article table; the metrics are taken from the exact read, by run
    table = llvip_ablation(export_dir)
    for column, source in (("R", "R_person"), ("P", "P_person"), ("mAP50", "mAP50"), ("mAP50-95", "mAP50_95")):
        table[column] = table["run_id"].map(runs.set_index("run_id")[source])
    table = table.rename(columns={"run_id": "index"})
    out = os.path.join(out_dir, "detection_ablation_table.csv")
    n = _write_csv(out, table, ["index", "seed", "fusion", "rgb_eq", "th_eq", "R", "P", "mAP50", "mAP50-95"], ("index", "seed"))
    print("wrote %s  (%d rows, %d conditions)" % (out, n, table.groupby(["fusion", "rgb_eq", "th_eq"]).ngroups))


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: export_web_data.py <export_dir> <out_dir>")
    export_dir, out_dir = sys.argv[1:3]
    os.makedirs(out_dir, exist_ok=True)
    export_mnist(export_dir, out_dir)
    export_yolo(export_dir, out_dir)


if __name__ == "__main__":
    main()
