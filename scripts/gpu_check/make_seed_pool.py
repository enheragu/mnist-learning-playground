#!/usr/bin/env python3
# encoding: utf-8
"""
Generates the seed pool of the cross-GPU variance study.

It is the piece that makes the seed-by-seed comparison possible: all machines
must train EXACTLY the same seeds, without coordination.
The original 2024 study used `random.randint()` without seeding the pool, so
its seeds were not reproducible (and for most models they were not even
recorded). That is why this study is regenerated from scratch.

Properties:
  - Deterministic: same MASTER_SEED -> same pools on any machine and
    Python version. Uses random.Random(), not the global RNG, so as not to
    depend on anything else that runs before.
  - Per model: each condition has its own list. Increasing N does not alter the
    seeds already present (they are generated in order and truncated), so the
    study can be extended without invalidating what has already been run.
  - Verifiable: a checksum is emitted, to be recorded on each machine.

Usage:
    python make_seed_pool.py                 # writes seed_pools.yaml
    python make_seed_pool.py --check         # checks the existing one without writing
"""

import argparse
import hashlib
import os
import random
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, "..", "..", "seed_pools.yaml"))

# DO NOT CHANGE once the study has started: changing it invalidates everything already run.
MASTER_SEED = 20260729

# Conditions and number of seeds. The order matters: it defines the execution
# order by priority (seed index outside, model inside), so that if a session is
# cut short, all machines are missing the same trials.
CONDITIONS = [
    # (name, n, note)
    ("SimplePerceptron",      200, "minimal GEMM, no hidden layers (control)"),
    ("HiddenLayerPerceptron", 200, "wide GEMM (analogous to BourginMLP in the CPU case)"),
    ("CNN_3L",                100, "shallow cuDNN"),
    ("DNN_6L",                100, "very wide and deep GEMM"),
    ("CNN_14L",               100, "deep cuDNN + BatchNorm (flagship model)"),
    ("CNN_14L_B10",            50, "extension: same network with batch size 10 (about 6x more optimizer steps per epoch)"),
]

SEED_MIN, SEED_MAX = 0, 2**32 - 1


def build_pools():
    """One independent generator per model, seeded reproducibly."""
    pools = {}
    for name, n, _ in CONDITIONS:
        # The sub-seed depends on the model name, not on its position: this way
        # reordering or adding conditions does not change the seeds of the others.
        sub = int(hashlib.sha256(f"{MASTER_SEED}:{name}".encode()).hexdigest()[:16], 16)
        rng = random.Random(sub)
        seen, seeds = set(), []
        while len(seeds) < n:
            s = rng.randint(SEED_MIN, SEED_MAX)
            if s not in seen:          # no repeats within a condition
                seen.add(s)
                seeds.append(s)
        pools[name] = seeds
    return pools


def checksum(pools):
    h = hashlib.sha256()
    for name in sorted(pools):
        h.update(name.encode())
        h.update(",".join(map(str, pools[name])).encode())
    return h.hexdigest()[:16]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="checks the existing file instead of writing it")
    args = ap.parse_args()

    pools = build_pools()
    cks = checksum(pools)

    doc = {
        "master_seed": MASTER_SEED,
        "checksum": cks,
        "conditions": [
            {"model": name, "n": n, "note": note} for name, n, note in CONDITIONS
        ],
        "pools": pools,
    }

    print(f"MASTER_SEED = {MASTER_SEED}")
    print(f"checksum    = {cks}\n")
    print(f"  {'condition':24} {'n':>4}  first seeds")
    for name, n, _ in CONDITIONS:
        head = ", ".join(str(s) for s in pools[name][:3])
        print(f"  {name:24} {n:4}  {head}, ...")
    total = sum(n for _, n, _ in CONDITIONS)
    print(f"\n  total trainings per machine: {total}")

    if args.check:
        if not os.path.exists(OUT):
            sys.exit(f"\nERROR: file not found: {OUT}")
        old = yaml.safe_load(open(OUT))
        if old.get("checksum") != cks:
            sys.exit(f"\nERROR: the existing file has checksum {old.get('checksum')}, "
                     f"expected {cks}. Someone changed MASTER_SEED or the conditions.")
        print(f"\n  {OUT}\n  -> checksum matches")
        return

    with open(OUT, "w") as f:
        f.write("# Seed pool of the cross-GPU variance study.\n")
        f.write("# GENERATED by scripts/gpu_check/make_seed_pool.py -- do not edit by hand.\n")
        f.write("# Regenerable: same MASTER_SEED -> same content.\n")
        f.write("# Record the checksum on each machine to detect whether any of them\n")
        f.write("# is running a different pool.\n")
        yaml.safe_dump(doc, f, sort_keys=False, default_flow_style=False)
    print(f"\n  written {OUT}")


if __name__ == "__main__":
    main()
